class LatencyModel:
    """
    Two-mode latency lookup for GraphMind v2 evaluation.

    Mode selection:
      - If settings.LATENCY_MEASURED_CSV_PATH exists: MODE B (measured).
      - Otherwise: MODE A (literature).
    Mode can be forced via constructor.

    All values are in milliseconds.
    """

    MODE_LITERATURE = "literature"
    MODE_MEASURED = "measured"

    def __init__(self, force_mode: Optional[str] = None) -> None:
        """
        Args:
            force_mode: Force "literature" or "measured" mode.
                        If None, auto-selects based on file availability.
        """
        self._measured_data: Dict[str, dict] = {}

        if force_mode:
            self._mode = force_mode
        elif os.path.exists(settings.LATENCY_MEASURED_CSV_PATH):
            self._mode = self.MODE_MEASURED
        else:
            self._mode = self.MODE_LITERATURE

        if self._mode == self.MODE_MEASURED:
            self._load_measured()

        logger.info(f"LatencyModel initialised in {self._mode} mode.")

    @property
    def mode(self) -> str:
        """Return the active mode: 'literature' or 'measured'."""
        return self._mode

    def cold_start_ms(self, app_id: str, stat: str = "mean") -> float:
        """
        Return cold start latency in milliseconds.

        Args:
            app_id: Android package ID.
            stat:   One of 'mean', 'median', 'p50', 'p95', 'p99'.
                    Stat selection only applies in measured mode.
        Returns:
            Latency in milliseconds.
        """
        return self._get(app_id, "cold_ms", stat)

    def warm_start_ms(self, app_id: str, stat: str = "mean") -> float:
        """Return warm start latency in milliseconds."""
        return self._get(app_id, "warm_ms", stat)

    def hot_start_ms(self, app_id: str, stat: str = "mean") -> float:
        """Return hot start latency in milliseconds."""
        return self._get(app_id, "hot_ms", stat)

    def latency_saved_ms(self, app_id: str, tier: str, stat: str = "mean") -> float:
        """
        Return latency saved vs cold start for the given tier.

        Args:
            app_id: Android package ID.
            tier:   'hot' or 'warm'. Returns 0 for 'cold' (no savings).
            stat:   Statistic to use for measured mode.

        Returns:
            Latency saved in milliseconds (always >= 0).
        """
        cold = self.cold_start_ms(app_id, stat)
        if tier == "hot":
            return max(0.0, cold - self.hot_start_ms(app_id, stat))
        if tier == "warm":
            return max(0.0, cold - self.warm_start_ms(app_id, stat))
        return 0.0

    def get_record(self, app_id: str) -> dict:
        """
        Return the full provenance record for an app.

        In literature mode: returns the _LITERATURE_RECORDS entry with all
        provenance fields (source, device_class, android_version, citation, etc.)

        In measured mode: returns the aggregated stats dict.
        """
        if self._mode == self.MODE_MEASURED:
            return self._measured_data.get(
                app_id, self._measured_data.get("default", {})
            )
        return _LITERATURE_RECORDS.get(app_id, _LITERATURE_RECORDS["default"])

    def get_all_records(self) -> Dict[str, dict]:
        """Return all records (literature or measured) keyed by app_id."""
        if self._mode == self.MODE_MEASURED:
            return dict(self._measured_data)
        return dict(_LITERATURE_RECORDS)

    def latency_report(self) -> List[dict]:
        """
        Return a list of per-app latency rows for report generation.

        Each row contains: app_id, mode, cold_ms, warm_ms, hot_ms, citation.
        """
        rows = []
        for app_id, record in self.get_all_records().items():
            if app_id == "default":
                continue
            rows.append({
                "app_id": app_id,
                "mode": self._mode,
                "cold_ms": record.get("cold_ms", 0.0),
                "warm_ms": record.get("warm_ms", 0.0),
                "hot_ms": record.get("hot_ms", 0.0),
                "device_class": record.get("device_class", ""),
                "citation": record.get("citation", ""),
                "measurement_date": record.get("measurement_date", ""),
            })
        return rows

    # ------------------------------------------------------------------
    # Private
    # ------------------------------------------------------------------

    def _get(self, app_id: str, field: str, stat: str) -> float:
        """Retrieve a latency value from the active data source."""
        if self._mode == self.MODE_MEASURED:
            return self._get_measured(app_id, field, stat)
        return self._get_literature(app_id, field)

    def _get_literature(self, app_id: str, field: str) -> float:
        """Look up a field from the literature records."""
        record = _LITERATURE_RECORDS.get(app_id, _LITERATURE_RECORDS["default"])
        return float(record.get(field, _LITERATURE_RECORDS["default"].get(field, 0.0)))

    def _get_measured(self, app_id: str, field: str, stat: str) -> float:
        """Look up a statistic from measured data."""
        record = self._measured_data.get(
            app_id, self._measured_data.get("default", {})
        )
        stat_key = f"{field}_{stat}"
        if stat_key in record:
            return float(record[stat_key])
        # Fall back to mean if requested stat not available
        mean_key = f"{field}_mean"
        if mean_key in record:
            return float(record[mean_key])
        # Final fallback to literature
        return self._get_literature(app_id, field)

    def _load_measured(self) -> None:
        """
        Load ADB-measured latency data from CSV.

        Expected CSV columns:
          app_id, start_type, mean_ms, median_ms, p50_ms, p95_ms, p99_ms

        start_type: "cold", "warm", "hot"

        Rows are aggregated into per-app records with keys like:
          cold_ms_mean, cold_ms_median, cold_ms_p50, cold_ms_p95, cold_ms_p99
          warm_ms_mean, ...
          hot_ms_mean, ...
        """
        path = settings.LATENCY_MEASURED_CSV_PATH
        if not os.path.exists(path):
            logger.warning(
                f"Measured latency CSV not found at {path}. "
                "Falling back to literature mode."
            )
            self._mode = self.MODE_LITERATURE
            return

        try:
            with open(path, newline="", encoding="utf-8") as fh:
                reader = csv.DictReader(fh)
                rows = list(reader)
        except Exception as exc:
            logger.error(f"Failed to load measured latency CSV: {exc}")
            self._mode = self.MODE_LITERATURE
            return

        data: Dict[str, dict] = {}
        for row in rows:
            app_id = row.get("app_id", "").strip()
            start_type = row.get("start_type", "").strip().lower()
            if not app_id or start_type not in ("cold", "warm", "hot"):
                continue
            if app_id not in data:
                data[app_id] = {
                    "source": "measured",
                    "device_class": row.get("device_class", "Samsung Galaxy A23"),
                    "android_version": row.get("android_version", "Android 12"),
                    "app_version": row.get("app_version", "unknown"),
                    "measurement_date": row.get("measurement_date", ""),
                    "citation": "ADB measurement via scripts/collect_app_latency.py",
                }
            field_prefix = f"{start_type}_ms"
            for stat in ("mean", "median", "p50", "p95", "p99"):
                csv_col = f"{stat}_ms"
                if csv_col in row:
                    try:
                        data[app_id][f"{field_prefix}_{stat}"] = float(row[csv_col])
                    except (ValueError, TypeError):
                        pass
            # Alias: cold_ms = cold_ms_mean for compatibility
            if f"{field_prefix}_mean" in data[app_id]:
                data[app_id][field_prefix] = data[app_id][f"{field_prefix}_mean"]

        self._measured_data = data
        logger.info(
            f"LatencyModel: loaded measured data for {len(data)} apps from {path}"
        )
